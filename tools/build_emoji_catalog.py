"""Offline Python oracle for the native, pinned Unicode/CLDR emoji catalog."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path


REPO_ROOT = Path(__file__).resolve().parents[1]
INPUT_PATH = REPO_ROOT / "node_modules" / ".yomux" / "emoji"
CLDR_VERSION = "47.0.0"
UNICODE_EMOJI_VERSION = "16.0"
LOCALES = {
    "ar": "ar", "de": "de", "en": "en", "es": "es", "fr": "fr", "he": "he", "hi": "hi",
    "it": "it", "ja": "ja", "ko": "ko", "nl": "nl", "pl": "pl", "pt-BR": "pt", "ru": "ru",
    "th": "th", "tr": "tr", "vi": "vi", "zh-Hans": "zh", "zh-Hant": "zh-Hant",
}


def pinned_input(name: str) -> bytes:
    manifest = json.loads((REPO_ROOT / "assets/runtime/browser-assets.json").read_bytes())
    expected = {path: record["sha256"] for path, record in manifest["files"].items()}
    for archive in manifest["archives"]:
        expected.update(archive["files"])
    path = INPUT_PATH / name
    try:
        data = path.read_bytes()
    except FileNotFoundError as error:
        raise ValueError("Emoji inputs are not prepared; run make build first") from error
    if hashlib.sha256(data).hexdigest() != expected[str(path.relative_to(REPO_ROOT))]:
        raise ValueError(f"Emoji input checksum mismatch: {name}; run make build to repair")
    return data


def emoji_sequence(text: str) -> list[tuple[str, str]]:
    result: list[tuple[str, str]] = []
    seen: set[str] = set()
    category = "symbols"
    for line in text.splitlines():
        if line.startswith("# group:"):
            category = line.partition(":")[2].strip().casefold().replace(" & ", "-").replace(" ", "-")
            continue
        data, separator, description = line.partition("#")
        if not separator or "; fully-qualified" not in data:
            continue
        glyph = description.strip().split(maxsplit=1)[0]
        if glyph and glyph not in seen:
            seen.add(glyph)
            result.append((glyph, category))
    return result


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True, help="private output file outside Git worktrees")
    args = parser.parse_args()
    args.output = args.output.resolve()
    if any((parent / ".git").exists() for parent in args.output.parents):
        parser.error("oracle output must be outside Git worktrees; make build owns checkout publication")
    emoji_test = pinned_input("emoji-test.data").decode("utf-8")
    glyphs = emoji_sequence(emoji_test)
    annotations: dict[str, dict] = {}
    for app_locale in LOCALES:
        annotations[app_locale] = {
            **json.loads(pinned_input(f"{app_locale}-annotations.json"))["annotations"]["annotations"],
            **json.loads(pinned_input(f"{app_locale}-annotationsDerived.json"))["annotationsDerived"]["annotations"],
        }
    records = []
    for glyph, category in glyphs:
        names: dict[str, str] = {}
        keywords: dict[str, list[str]] = {}
        for locale, catalog in annotations.items():
            entry = catalog.get(glyph) or catalog.get(glyph.replace("\ufe0f", ""))
            if not isinstance(entry, dict):
                continue
            tts = entry.get("tts")
            default = entry.get("default")
            if isinstance(tts, list) and tts:
                names[locale] = str(tts[0])
            if isinstance(default, list):
                keywords[locale] = [str(value) for value in default]
        if "en" in names:
            records.append({"emoji": glyph, "category": category, "names": names, "keywords": keywords})
    text = (
        f"// Generated by tools/build_emoji_catalog.py from Unicode Emoji {UNICODE_EMOJI_VERSION} and CLDR {CLDR_VERSION}.\n"
        "// Unicode data license: https://www.unicode.org/license.txt\n"
        f"globalThis.YOMUX_EMOJI_DATA = {json.dumps(records, ensure_ascii=False, separators=(',', ':'))};\n"
        "globalThis.YOLOMUX_EMOJI_DATA = globalThis.YOMUX_EMOJI_DATA;\n"
    )
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(text, encoding="utf-8")
    print(f"wrote {len(records)} emoji records to {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
