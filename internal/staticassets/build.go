const header = "/* GENERATED by tools/static_build.py from static_src/ - DO NOT EDIT %s; edit the partials and rebuild. */\n"

// Build validates every input before returning any output for publication.
func Build(root string) (map[string][]byte, error) {
	var manifest map[string][]string
	if err := readJSON(filepath.Join(root, "static_src", "build-manifest.json"), &manifest); err != nil {
		return nil, err
	}
	if len(manifest) == 0 {
		return nil, errors.New("empty asset manifest")
	}
	outputs := make(map[string][]byte)
	for asset, parts := range manifest {
		if !filepath.IsLocal(asset) || asset != filepath.Base(asset) || len(parts) == 0 || (!strings.HasSuffix(asset, ".js") && !strings.HasSuffix(asset, ".css")) {
			return nil, fmt.Errorf("invalid asset %q", asset)
		}
		var text strings.Builder
		fmt.Fprintf(&text, header, asset)
		for _, part := range parts {
			if !filepath.IsLocal(part) {
				return nil, fmt.Errorf("asset input escapes source root: %q", part)
			}
			data, err := os.ReadFile(filepath.Join(root, part))
			if err != nil {
				return nil, err
			}
			if !utf8.Valid(data) {
				return nil, fmt.Errorf("invalid UTF-8 in %s", part)
			}
			if strings.HasSuffix(asset, ".css") {
				if err := validateCSS(string(data)); err != nil {
					return nil, fmt.Errorf("%s: %w", part, err)
				}
			}
			// Path.read_text used universal newlines in the retired builder.
			text.WriteString(strings.ReplaceAll(strings.ReplaceAll(string(data), "\r\n", "\n"), "\r", "\n"))
		}
		value := text.String()
		if strings.Contains(value, "__YOMUX_SEARCH_RANK_WEIGHTS__") {
			weights, err := os.ReadFile(filepath.Join(root, "internal", "finder", "search_rank_weights.json"))
			if err != nil {
				return nil, err
			}
			var compact bytes.Buffer
			if err := json.Compact(&compact, weights); err != nil {
				return nil, err
			}
			value = strings.ReplaceAll(value, "__YOMUX_SEARCH_RANK_WEIGHTS__", compact.String())
		}
		outputs[asset] = []byte(value)
	}
	catalogs, err := buildLocales(root)
	if err != nil {
		return nil, err
	}
	for name, data := range catalogs {
		outputs[filepath.Join("locales", name+".json")] = data
	}
	return outputs, nil
}

func readJSON(path string, destination any) error {
	data, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	if !utf8.Valid(data) {
		return fmt.Errorf("invalid UTF-8 JSON in %s", path)
	}
	if err := json.Unmarshal(data, destination); err != nil {
		return fmt.Errorf("%s: %w", path, err)
	}
	return nil
}

func buildLocales(root string) (map[string][]byte, error) {
	registry, err := locales.Load(root)
	if err != nil {
		return nil, err
	}
	localizer, err := loadPseudo(root)
	if err != nil {
		return nil, err
	}
	catalogs := make(map[string]map[string]string)
	for _, locale := range registry {
		var catalog map[string]string
		if err := readCatalog(filepath.Join(root, "static_src", "locales", locale.Code+".json"), &catalog); err != nil {
			return nil, err
		}
		catalogs[locale.Code] = catalog
	}
	source, ok := catalogs["en"]
	if !ok || len(source) == 0 {
		return nil, errors.New("missing English source catalog")
	}
	paths, err := filepath.Glob(filepath.Join(root, "static_src", "locales", "*.json"))
	if err != nil {
		return nil, err
	}
	for _, path := range paths {
		locale := strings.TrimSuffix(filepath.Base(path), ".json")
		if locale != "en-XA" {
			if _, ok := catalogs[locale]; !ok {
				return nil, fmt.Errorf("unregistered source locale %s", locale)
			}
		}
	}
	for _, locale := range registry {
		expected := make(map[string]bool, len(source))
		for key := range source {
			expected[key] = true
		}
		categories := locale.PluralCategories
		seenCategories := make(map[string]bool)
		for _, category := range categories {
			if seenCategories[category] || !validCategory(category) {
				return nil, fmt.Errorf("invalid plural category for %s", locale.Code)
			}
			seenCategories[category] = true
		}
		if !seenCategories["other"] {
			return nil, fmt.Errorf("missing other plural category for %s", locale.Code)
		}
		if len(categories) == 0 {
			return nil, fmt.Errorf("missing plural categories for %s", locale.Code)
		}
		for key := range source {
			if !strings.HasSuffix(key, ".one") {
				continue
			}
			base := strings.TrimSuffix(key, ".one")
			if _, ok := source[base+".other"]; !ok {
				continue
			}
			for _, category := range categories {
				expected[base+"."+category] = true
			}
		}
		catalog := catalogs[locale.Code]
		for key := range expected {
			if _, ok := catalog[key]; !ok {
				return nil, fmt.Errorf("%s missing key %s", locale.Code, key)
			}
		}
		for key, value := range catalog {
			if !expected[key] {
				return nil, fmt.Errorf("%s has unknown key %s", locale.Code, key)
			}
			sourceKey := key
			if _, ok := source[sourceKey]; !ok {
				if at := strings.LastIndexByte(key, '.'); at >= 0 {
					sourceKey = key[:at] + ".other"
				}
			}
			if err := localizer.validateTranslation(locale.Code, key, source[sourceKey], value); err != nil {
				return nil, err
			}
		}
	}
	pseudo := make(map[string]string, len(source))
	for key, value := range source {
		pseudo[key] = localizer.pseudo(value)
	}
	catalogs["en-XA"] = pseudo
	outputs := make(map[string][]byte, len(catalogs))
	for locale, catalog := range catalogs {
		data, err := catalogJSON(catalog)
		if err != nil {
			return nil, err
		}
		outputs[locale] = data
	}
	return outputs, nil
}

// catalogJSON retains the readable, Unicode-preserving wire format of shipped catalogs.
func catalogJSON(catalog map[string]string) ([]byte, error) {
	var output bytes.Buffer
	encoder := json.NewEncoder(&output)
	encoder.SetEscapeHTML(false)
	encoder.SetIndent("", "  ")
	if err := encoder.Encode(catalog); err != nil {
		return nil, err
	}
	return literalSeparators(output.Bytes()), nil
}

type pseudoSpec struct {
	TokenPattern              string              `json:"token_pattern"`
	AccentFrom                string              `json:"accent_from"`
	AccentTo                  string              `json:"accent_to"`
	PlaceholderPattern        string              `json:"placeholder_pattern"`
	ProtectedTokenPattern     string              `json:"protected_token_pattern"`
	TranslatableCodeKeys      []string            `json:"translatable_code_keys"`
	OptionalBlankTranslations map[string][]string `json:"optional_blank_translations"`
}

type pseudoLocalizer struct {
	tokens       *regexp.Regexp
	accents      map[rune]rune
	placeholders *regexp.Regexp
	protected    *regexp.Regexp
	spec         pseudoSpec
}

func loadPseudo(root string) (*pseudoLocalizer, error) {
	var spec pseudoSpec
	if err := readJSON(filepath.Join(root, "static_src", "pseudo-locale.json"), &spec); err != nil {
		return nil, err
	}
	pattern, err := compileTokenGrammar(spec.TokenPattern)
	if err != nil {
		return nil, err
	}
	from, to := []rune(spec.AccentFrom), []rune(spec.AccentTo)
	if len(from) == 0 || len(from) != len(to) || spec.TokenPattern == "" {
		return nil, errors.New("invalid pseudo locale specification")
	}
	accents := make(map[rune]rune, len(from))
	for i, r := range from {
		accents[r] = to[i]
	}
	placeholders, err := regexp.Compile(spec.PlaceholderPattern)
	if err != nil {
		return nil, err
	}
	protected, err := compileTokenGrammar(spec.ProtectedTokenPattern)
	if err != nil {
		return nil, err
	}
	if spec.PlaceholderPattern == "" || spec.ProtectedTokenPattern == "" {
		return nil, errors.New("missing token grammar")
	}
	return &pseudoLocalizer{tokens: pattern, accents: accents, placeholders: placeholders, protected: protected, spec: spec}, nil
}

// Pseudo leaves executable fragments and substitutions byte-for-byte intact.
func (p *pseudoLocalizer) pseudo(value string) string {
	accent := func(text string) string {
		return strings.Map(func(r rune) rune {
			if a, ok := p.accents[r]; ok {
				return a
			}
			return r
		}, text)
	}
	var out strings.Builder
	visible, previous := 0, 0
	for _, pair := range tokenSpans(p.tokens, value) {
		text := value[previous:pair[0]]
		out.WriteString(accent(text))
		visible += utf8.RuneCountInString(text)
		segment := value[pair[0]:pair[1]]
		// The reference builder tests each split segment in isolation. Preserve
		// its boundary-sensitive accenting separately from original-span padding.
		isolated := tokenSpans(p.tokens, segment)
		if len(isolated) == 1 && isolated[0][0] == 0 && isolated[0][1] == len(segment) {
			out.WriteString(segment)
		} else {
			out.WriteString(accent(segment))
		}
		previous = pair[1]
	}
	text := value[previous:]
	out.WriteString(accent(text))
	visible += utf8.RuneCountInString(text)
	padding := max(1, int(math.RoundToEven(float64(visible)*0.4)))
	return "⟦" + out.String() + strings.Repeat("·", padding) + "⟧"
}

// Publish atomically replaces individual files after all inputs have been validated.
// The caller must own the destination (a private build tree or a writer lease).
func Publish(destination string, outputs map[string][]byte, check bool) ([]string, error) {
	var err error
	destination, err = mutablefs.Canonical(destination)
	if err != nil {
		return nil, err
	}
	names := make([]string, 0, len(outputs))
	for name := range outputs {
		names = append(names, name)
	}
	sort.Strings(names)
	// Preflight the complete set before publishing the first file. A private
	// root does not confer ownership on symlinked descendants into another tree.
	for _, name := range names {
		if !filepath.IsLocal(name) {
			return nil, fmt.Errorf("output escapes destination: %q", name)
		}
		path := filepath.Join(destination, name)
		if err := ownedOutputPath(path); err != nil {
			return nil, err
		}
	}
	changed := make([]string, 0)
	for _, name := range names {
		path := filepath.Join(destination, name)
		if err := ownedOutputPath(path); err != nil {
			return nil, err
		}
		current, err := os.ReadFile(path)
		if err != nil && !errors.Is(err, os.ErrNotExist) {
			return nil, err
		}
		if err == nil && bytes.Equal(current, outputs[name]) {
			continue
		}
		changed = append(changed, name)
		if check {
			continue
		}
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return nil, err
		}
		if err := ownedOutputPath(path); err != nil {
			return nil, err
		}
		staged, err := atomicfile.Stage(path, outputs[name])
		if err != nil {
			return nil, err
		}
		// Stage is private by default; browser assets must retain their public file mode.
		mode := os.FileMode(0o644)
		if info, err := os.Stat(path); err == nil {
			mode = info.Mode().Perm()
		} else if !errors.Is(err, os.ErrNotExist) {
			staged.Cleanup()
			return nil, err
		}
		// Commit after setting mode; readers never see a private-mode publication window.
		if err := staged.Chmod(mode); err != nil {
			staged.Cleanup()
			return nil, err
		}
		err = staged.Commit()
		staged.Cleanup()
		if err != nil {
			return nil, err
		}
	}
	return changed, nil
}

func ownedOutputPath(path string) error {
	canonical, err := mutablefs.Canonical(path)
	if err != nil {
		return err
	}
	if canonical != path {
		return fmt.Errorf("output contains a symlink: %s", path)
	}
	return nil
}
